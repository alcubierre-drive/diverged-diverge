static char graphene_hr_dat_fname[1024] = {0};

const char* gen_graphene_hr_dat( int use_fplo ) {
    if (use_fplo) {
        snprintf(graphene_hr_dat_fname, 1023, "./.graphene_+hamdata.XXXXXX");
    } else {
        snprintf(graphene_hr_dat_fname, 1023, "./.graphene_hr_dat.XXXXXX");
    }
    int fd = mkstemp( graphene_hr_dat_fname );

    if (fd == -1) {
        mpi_err_printf( "could not create temporary file '%s'\n", graphene_hr_dat_fname );
    }

    if (use_fplo) {
        ssize_t nbytes_written = write( fd, _hamdata, _hamdata_len );
        if (nbytes_written == -1 || nbytes_written < (ssize_t)_hamdata_len) {
            mpi_err_printf("error writing file '%s'\n", graphene_hr_dat_fname);
        }
    } else {
        ssize_t nbytes_written = write( fd, graphene_dat, graphene_dat_len );
        if (nbytes_written == -1 || nbytes_written < (ssize_t)graphene_dat_len) {
            mpi_err_printf("error writing file '%s'\n", graphene_hr_dat_fname);
        }
    }
    close( fd );
    return graphene_hr_dat_fname;
}

